#!/usr/bin/env python3
"""
Regenerate the kernel-entry machine code embedded in the JavaScript port.

The JS interpreter and the Unicorn reference must execute byte-identical
instructions, otherwise "both implementations agree" proves nothing. So the
listing lives once, in tests/test_a5_boot.py, is assembled by keystone, and the
resulting bytes are emitted here as a checked-in JS constant.

    python3 tools/gen_entry_js.py [--check]

--check exits non-zero if the committed constant has drifted from what keystone
produces now, which is what CI (or a careful human) wants.
"""

import json
import os
import re
import sys

from jsns import PREAMBLE

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "tests"))

OUT = os.path.join(ROOT, "web", "entrycode.js")

HEADER = """// GENERATED by tools/gen_entry_js.py - do not edit by hand.
//
// Machine code for XNU's arm start() entry sequence on k93ap, assembled with
// keystone from the listing in tests/test_a5_boot.py. The JavaScript ARMv7
// interpreter and the Unicorn reference implementation both execute exactly
// these bytes, so agreement between them is meaningful.
//
// Load address: PA 0x400860C8 (VA 0x800860C8).
"""


def assemble(src):
    """Keystone's ARM frontend treats ';' as a statement separator, not a comment."""
    from keystone import KS_ARCH_ARM, KS_MODE_ARM, Ks

    clean = []
    for line in src.splitlines():
        for marker in ("//", ";"):
            cut = line.find(marker)
            if cut != -1:
                line = line[:cut]
        if line.strip():
            clean.append(line)
    ks = Ks(KS_ARCH_ARM, KS_MODE_ARM)
    encoding, _ = ks.asm("\n".join(clean), 0)
    return bytes(bytearray(encoding))


def main():
    check = "--check" in sys.argv
    path = os.path.join(ROOT, "tests", "test_a5_boot.py")
    with open(path, encoding="utf-8") as fh:
        body = re.search(r'START_S = """(.*?)"""', fh.read(), re.S).group(1)
    code = assemble(body)

    lines = []
    for off in range(0, len(code), 16):
        chunk = code[off:off + 16]
        lines.append("    " + ", ".join("0x%02X" % b for b in chunk) + ",")
    payload = "\n".join(lines)

    text = (
        HEADER
        + "\n" + PREAMBLE + "\n"
        + "\nA5.ENTRY_PA = 0x400860C8;\nA5.ENTRY_VA = 0x800860C8;\n"
        + "A5.HANDOFF  = 0x80017C41;   // from __nl_symbol_ptr, thumb bit set\n\n"
        + "A5.ENTRY_CODE = new Uint8Array([\n" + payload + "\n]);\n\n"
        + "// Listing, kept next to the bytes so the two cannot silently diverge.\n"
        + "A5.ENTRY_SOURCE = " + json.dumps(body.strip()) + ";\n"
        + "\nif (typeof module !== 'undefined' && module.exports) {\n"
        + "    module.exports = A5;\n}\n"
    )

    if check:
        old = ""
        if os.path.exists(OUT):
            with open(OUT, encoding="utf-8") as fh:
                old = fh.read()
        if old != text:
            sys.stderr.write("%s is out of date; run tools/gen_entry_js.py\n" % OUT)
            return 1
        print("%s is up to date (%d bytes of code)" % (OUT, len(code)))
        return 0

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s: %d instructions, %d bytes" % (OUT, len(code) // 4, len(code)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
