#!/usr/bin/env python3
"""Generate src/psx/TinyFont.java - a built-in 5x7 bitmap font.

The MIDlet draws *all* of its text with this font instead of Graphics.drawString()
because:

  * many Java ME devices ship fonts without Cyrillic, so the whole Russian UI
    came out blank ("текст пропал");
  * some firmware ignores Graphics.setFont() and always uses a huge font, which
    pushed labels off screen;
  * a bitmap font guarantees identical layout on every handset.

Glyphs are rendered once from DejaVu Sans Mono (descender aware) at 128 px,
downsampled to a 5x7 box and stored as 7 printable characters per glyph
(each character = one row, value 0..31 encoded as chr(0x20 + bits)).

Usage:  python3 tools/mkfont.py [--check]
"""

import sys
from PIL import Image, ImageDraw, ImageFont

SRC_FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
OUT = "src/psx/TinyFont.java"
PX = 128
CAP = 6          # rows above the baseline
DESC = 1         # rows below the baseline
GLYPH_W = 5      # glyph box width
CELL_W = 6       # advance

CHARS = [chr(c) for c in range(32, 127)]
CHARS += ["\u0401", "\u0451"]
CHARS += [chr(c) for c in range(0x410, 0x450)]
CHARS += ["\u00ab", "\u00bb", "\u2014", "\u2026", "\u2116", "\u00b0", "\u2192", "\u2190", "\u25b6"]


def render(font, ch):
    big = Image.new("L", (PX * 3, PX * 3), 0)
    d = ImageDraw.Draw(big)
    base = PX * 2
    d.text((PX, base), ch, fill=255, font=font, anchor="ls")
    bbox = big.getbbox()
    if bbox is None:
        return [0] * 7
    # keep the glyph's position relative to the baseline
    x0, y0, x1, y1 = bbox
    asc, desc = font.getmetrics()
    scale = CAP / (asc * 0.76)          # cap height ~ 0.76 * ascent for DejaVu
    w = max(1, min(GLYPH_W, int(round((x1 - x0) * scale))))
    top = int(round((base - y0) * scale))       # pixels above the baseline
    bottom = int(round((y1 - base) * scale))    # pixels below the baseline
    h = min(CAP + DESC, max(1, top + max(1, bottom)))
    crop = big.crop((x0, y0, x1, y1)).resize((w, h), Image.LANCZOS)
    rows = []
    base_row = CAP - 1                  # row index of the last row above baseline
    start = base_row - top + 1
    for r in range(7):
        src_row = r - start
        bits = 0
        if 0 <= src_row < h:
            for x in range(w):
                if crop.getpixel((x, src_row)) >= 96:
                    bits |= 1 << (GLYPH_W - 1 - x)
        rows.append(bits)
    return rows


def main():
    font = ImageFont.truetype(SRC_FONT, PX)
    data = []
    for ch in CHARS:
        rows = render(font, ch)
        data.extend(rows)
    # plain hex encoding: 2 digits per row, no escapes at all
    escaped = "".join("%02x" % b for b in data)
    esc_chars = "".join("\\%03o" % ord(c) if ord(c) < 128 else "\\u%04x" % ord(c) for c in CHARS)

    lines = []
    lines.append("package psx;")
    lines.append("")
    lines.append("import javax.microedition.lcdui.Graphics;")
    lines.append("")
    lines.append("/**")
    lines.append(" * Built-in 5x7 bitmap font (ASCII + Cyrillic). Generated by")
    lines.append(" * tools/mkfont.py - do not edit by hand.")
    lines.append(" *")
    lines.append(" * Every label of the MIDlet is drawn with this font, so text is")
    lines.append(" * visible even on handsets whose system font has no Cyrillic glyphs")
    lines.append(" * or ignores Graphics.setFont().")
    lines.append(" */")
    lines.append("public final class TinyFont {")
    lines.append("")
    lines.append("    public static final int WIDTH = %d;" % CELL_W)
    lines.append("    public static final int HEIGHT = 8;")
    lines.append("    private static final int GLYPH_W = %d;" % GLYPH_W)
    lines.append("    private static final int ROWS = 7;")
    lines.append("")
    lines.append("    /** Printable charset, one char per glyph, in table order. */")
    lines.append("    private static final String CHARS = \"%s\";" % esc_chars)
    lines.append("")
    lines.append("    /** 14 hex digits per glyph: 7 rows, 2 digits each, 5 low bits = pixels. */")
    # split the blob over several concatenated literals to keep lines short
    chunks = [escaped[i:i + 720] for i in range(0, len(escaped), 720)]
    for i, c in enumerate(chunks):
        prefix = "    private static final String DATA =" if i == 0 else "        +"
        suffix = ";" if i == len(chunks) - 1 else ""
        lines.append("%s \"%s\"%s" % (prefix, c, suffix))
    lines.append("")
    lines.append("    private TinyFont() { }")
    lines.append("")
    lines.append("    /** Fallback index: '?' */")
    lines.append("    private static final int FALLBACK = %d;" % CHARS.index("?"))
    lines.append("")
    lines.append("    private static int glyphIndex(char c) {")
    lines.append("        if (c >= 32 && c < 127) return c - 32;")
    lines.append("        if (c == '\\u0401') return %d;" % CHARS.index("\u0401"))
    lines.append("        if (c == '\\u0451') return %d;" % CHARS.index("\u0451"))
    lines.append("        if (c >= '\\u0410' && c <= '\\u044f') return %d + (c - '\\u0410');"
                 % CHARS.index(chr(0x410)))
    lines.append("        int extra = EXTRA.indexOf(c);")
    lines.append("        return extra < 0 ? FALLBACK : %d + extra;" % CHARS.index("\u00ab"))
    lines.append("    }")
    lines.append("")
    lines.append("    /** Extra glyphs outside the ASCII / Cyrillic ranges. */")
    lines.append("    private static final String EXTRA = \"\u00ab\u00bb\u2014\u2026\u2116\u00b0\u2192\u2190\u25b6\";")
    lines.append("")
    lines.append("    private static int hex(char c) {")
    lines.append("        if (c >= '0' && c <= '9') return c - '0';")
    lines.append("        return c - 'a' + 10;")
    lines.append("    }")
    lines.append("")
    lines.append("    public static int stringWidth(String s) {")
    lines.append("        return s == null ? 0 : s.length() * WIDTH;")
    lines.append("    }")
    lines.append("")
    lines.append("    public static int charWidth(char c) { return WIDTH; }")
    lines.append("")
    lines.append("    /** Human readable form: replaces glyphs this font cannot draw. */")
    lines.append("    private static char mapChar(char c) { return c; }")
    lines.append("")
    lines.append("    public static void draw(Graphics g, String s, int x, int y, int anchor) {")
    lines.append("        draw(g, s, x, y, anchor, false, 1);")
    lines.append("    }")
    lines.append("")
    lines.append("    public static void draw(Graphics g, String s, int x, int y, int anchor,")
    lines.append("                            boolean bold) {")
    lines.append("        draw(g, s, x, y, anchor, bold, 1);")
    lines.append("    }")
    lines.append("")
    lines.append("    public static void draw(Graphics g, String s, int x, int y, int anchor,")
    lines.append("                            boolean bold, int scale) {")
    lines.append("        if (s == null || s.length() == 0) return;")
    lines.append("        if (scale < 1) scale = 1;")
    lines.append("        int w = stringWidth(s) * scale;")
    lines.append("        int h = HEIGHT * scale;")
    lines.append("        int ax = anchor & 0x0f;")
    lines.append("        int ay = anchor & 0xf0;")
    lines.append("        if (ax == Graphics.HCENTER) x -= w / 2;")
    lines.append("        else if (ax == Graphics.RIGHT) x -= w;")
    lines.append("        if (ay == Graphics.BOTTOM) y -= h;")
    lines.append("        else if (ay == Graphics.BASELINE) y -= 6 * scale;")
    lines.append("        for (int i = 0; i < s.length(); i++) {")
    lines.append("            int gi = glyphIndex(s.charAt(i));")
    lines.append("            int gx = x + i * WIDTH * scale;")
    lines.append("            for (int row = 0; row < ROWS; row++) {")
    lines.append("                int p = (gi * ROWS + row) * 2;")
    lines.append("                int bits = (hex(DATA.charAt(p)) << 4) | hex(DATA.charAt(p + 1));")
    lines.append("                if (bits == 0) continue;")
    lines.append("                int col = 0;")
    lines.append("                while (col < GLYPH_W) {")
    lines.append("                    if ((bits & (1 << (GLYPH_W - 1 - col))) == 0) { col++; continue; }")
    lines.append("                    int run = 1;")
    lines.append("                    while (col + run < GLYPH_W")
    lines.append("                            && (bits & (1 << (GLYPH_W - 1 - col - run))) != 0) run++;")
    lines.append("                    g.fillRect(gx + col * scale, y + row * scale, run * scale, scale);")
    lines.append("                    /* Bold is expressed with colour, not a second pass:")
    lines.append("                       at 5x7 a doubled glyph turns Cyrillic into mush. */")
    lines.append("                    col += run;")
    lines.append("                }")
    lines.append("            }")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    /** Draws a string clipped to maxW pixels, ending with \"...\" when needed. */")
    lines.append("    public static String ellipsize(String s, int maxW) {")
    lines.append("        if (s == null) return \"\";")
    lines.append("        int maxChars = maxW / WIDTH;")
    lines.append("        if (maxChars < 4) maxChars = 4;")
    lines.append("        if (s.length() <= maxChars) return s;")
    lines.append("        return s.substring(0, maxChars - 3) + \"...\";")
    lines.append("    }")
    lines.append("}")
    src = "\n".join(lines) + "\n"
    open(OUT, "w").write(src)
    print("[font] %d glyphs, %d bytes -> %s" % (len(CHARS), len(src), OUT))

    # quick visual check
    def show(text):
        rows = ["   " for _ in range(7)]
        for ch in text:
            gi = CHARS.index(ch) if ch in CHARS else CHARS.index("?")
            for r in range(7):
                v = data[gi * 7 + r]
                rows[r] += "".join("#" if (v >> (4 - x)) & 1 else "." for x in range(5)) + " "
        print("\n".join(rows))

    if "--check" in sys.argv:
        show("PS1J2ME")
        show("\u041f\u0440\u0438\u0432\u0435\u0442")


if __name__ == "__main__":
    main()
